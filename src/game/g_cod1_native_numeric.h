 if((int16_t)e<=0){
  e=(e-1)&0xffff;
  if((int16_t)e<0){unsigned shift=(unsigned)(-(int16_t)e);e=(e+shift)&0xffff;
   while(shift--){sticky|=p[0]&1;C1NShiftRight(p);}if(sticky)p[0]|=1;}
 }
