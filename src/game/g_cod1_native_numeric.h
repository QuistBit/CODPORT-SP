  ++p;if(p<end&&(*p=='+'||*p=='-')){negative=*p=='-';++p;}
  while(p<end&&C1NDigit((unsigned char)*p)){
   if(exponent<=5200){exponent=exponent*10+*p-'0';if(exponent>5200)exponent=5201;}++p;
  }
